import Foundation

enum AgentEvent {
    case session(String)
    case text(String)
    case tool(String)
    case done(String)
    case failed(String)
    case raw(String)
}

/// Drives `claude -p` (Claude Code headless) and parses its stream-json output.
enum Agent {
    static let allowedTools = [
        "Read", "Edit", "Write", "Glob", "Grep",
        "Bash(./build.sh)", "Bash(./build.sh:*)", "Bash(swift build:*)", "Bash(swift package:*)",
    ].joined(separator: ",")

    static let systemPrompt = """
    You are Forge's builder agent. The current directory is a standalone macOS SwiftUI app \
    (Swift Package, macOS 14+, no Xcode project). Read APP.md first for context.

    Rules:
    - Make the change the user asks for by editing files under Sources/. Split code into files as it grows.
    - After editing, run ./build.sh and fix every compiler error until it succeeds.
    - Do not launch or open the app; Forge relaunches it automatically after you finish.
    - Persist user data (JSON in ~/Library/Application Support/<app name>/) so relaunches don't lose state.
    - Sources/ForgeSupport.swift is generated by Forge: never edit it. Keep the `.commands { ForgeCommands() }` modifier.
    - For any AI feature (summarising, extracting, classifying, rewriting, generating text), use \
    `ForgeAI.ask(...)` from ForgeSupport.swift. Read its doc comment for usage. Never call AI APIs directly, \
    never ask the user for API keys. It accepts `images: [NSImage]` when the AI needs to look at photos or \
    screenshots. Show a ProgressView while waiting and show errors in the UI.
    - The app icon is defined in icon.json: `symbol` (an SF Symbol name), `background` (two hex colours, \
    top-to-bottom gradient), `foreground` (symbol colour) and `art_prompt` (one sentence describing illustrated \
    artwork). To change the icon, edit icon.json; Forge redraws it. Never create icon files yourself.
    - Keep APP.md current: what the app does and how the code is organised.
    - Finish with one or two plain sentences describing what changed.
    """

    static func parse(_ line: String) -> [AgentEvent] {
        guard let data = line.data(using: .utf8),
              let obj = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let type = obj["type"] as? String
        else { return line.trimmed.isEmpty ? [] : [.raw(line)] }

        switch type {
        case "system":
            if obj["subtype"] as? String == "init", let id = obj["session_id"] as? String {
                return [.session(id)]
            }
        case "assistant":
            let content = (obj["message"] as? [String: Any])?["content"] as? [[String: Any]] ?? []
            return content.compactMap { block -> AgentEvent? in
                switch block["type"] as? String {
                case "text":
                    guard let text = (block["text"] as? String)?.trimmed, !text.isEmpty else { return nil }
                    return .text(text)
                case "tool_use":
                    return .tool(describe(block["name"] as? String ?? "Tool", block["input"] as? [String: Any] ?? [:]))
                default:
                    return nil
                }
            }
        case "result":
            let failed = obj["is_error"] as? Bool ?? false
            let seconds = (obj["duration_ms"] as? Double ?? 0) / 1000
            let cost = obj["total_cost_usd"] as? Double ?? 0
            let summary = AgentEvent.done(String(format: "%@ · %.0fs · $%.2f", failed ? "Agent error" : "Agent done", seconds, cost))
            return failed ? [summary, .failed(obj["result"] as? String ?? "Unknown error")] : [summary]
        default:
            break
        }
        return []
    }

    private static func describe(_ name: String, _ input: [String: Any]) -> String {
        if let path = input["file_path"] as? String { return "\(name) \((path as NSString).lastPathComponent)" }
        if let command = input["command"] as? String { return "\(name): \(command)" }
        if let pattern = input["pattern"] as? String { return "\(name) \(pattern)" }
        return name
    }
}

enum Shell {
    /// GUI apps don't inherit the user's shell PATH, so add the usual install locations.
    private static let extraPath = ["~/.local/bin", "/opt/homebrew/bin", "/usr/local/bin"]
        .map { ($0 as NSString).expandingTildeInPath }
        .joined(separator: ":")

    /// Runs a zsh command, streaming merged stdout/stderr line by line. Returns the exit status.
    static func run(
        _ command: String,
        cwd: URL,
        env: [String: String] = [:],
        onLine: @escaping @MainActor (String) -> Void
    ) async -> Int32 {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/bin/zsh")
        process.arguments = ["-lc", "export PATH=\"\(extraPath):$PATH\"; \(command)"]
        process.currentDirectoryURL = cwd
        var environment = ProcessInfo.processInfo.environment.merging(env) { $1 }
        environment.removeValue(forKey: "CLAUDECODE")
        process.environment = environment

        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = pipe
        process.standardInput = FileHandle.nullDevice

        do {
            try process.run()
        } catch {
            await onLine("Could not start process: \(error.localizedDescription)")
            return -1
        }
        do {
            for try await line in pipe.fileHandleForReading.bytes.lines {
                await onLine(line)
            }
        } catch {}
        process.waitUntilExit()
        return process.terminationStatus
    }
}
